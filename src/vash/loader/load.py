"""Clean-slate loader (C-13)."""
import shutil
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from vash.core.freeze import load_freeze
from vash.core.paths import vash_root

@dataclass(frozen=True)
class LoadReport:
    written: list[str]
    removed: list[str]
    warnings: list[str]

def generate_claude_md(repo_root: Path) -> str:
    """Generate CLAUDE.md from laws.md and project-stack.json."""
    try:
        freeze = load_freeze(repo_root)
        laws_path = vash_root() / "method" / "laws.md"
        laws = laws_path.read_text(encoding="utf-8") if laws_path.exists() else ""
    except Exception:
        laws = "# VASH Laws\n(not found)"
        freeze = None

    lines = ["# CLAUDE.md", "", "This file is generated by VASH. Do not edit by hand.", ""]
    lines.append("## Project Stack")
    if freeze:
        lines.append(f"- **Stack Pack**: {freeze.pack[0]} v{freeze.pack[1]}")
        lines.append(f"- **Forge**: {freeze.forge[0]}")
        lines.append(f"- **CI**: {freeze.ci[0]}")
        lines.append(f"- **Cloud**: {freeze.cloud[0]}")
        lines.append(f"- **Floor**: {freeze.floor}")
    else:
        lines.append("- (No valid project-stack.json found)")
    lines.extend(["", "## Laws and Rules", "", laws])
    return "\n".join(lines) + "\n"

MANAGED_FILE = ".vash-managed"


def _remove_managed(target: Path, dry_run: bool) -> list[str]:
    """Remove only what an earlier `vash load` wrote; anything added by hand stays."""
    record = target / MANAGED_FILE
    if not record.exists():
        return []
    removed = []
    for name in record.read_text(encoding="utf-8").split():
        path = target / name
        if not path.exists():
            continue
        if not dry_run:
            if path.is_dir():
                shutil.rmtree(path)
            else:
                path.unlink()
        removed.append(str(path))
    return removed


def generate_agents_md(repo_root: Path) -> str:
    """AGENTS.md: the same laws as CLAUDE.md, plus the agent roles and skills, for every coding tool."""
    from vash.loader.skills import find_agents, find_skills

    body = generate_claude_md(repo_root).split("\n", 4)[4]
    try:
        freeze = load_freeze(repo_root)
        skill_ids = [s["id"] for s in freeze.data.get("skills", [])]
        agent_ids = [a["id"] for a in freeze.data.get("agents", [])]
    except Exception:
        skill_ids, agent_ids = [], []
    skills = find_skills(repo_root)
    agents = find_agents(repo_root)
    skill_ids += [n for n, s in skills.items() if s.origin == "project" and n not in skill_ids]
    agent_ids += [n for n, a in agents.items() if a.origin == "project" and n not in agent_ids]

    lines = ["# AGENTS.md", "", "This file is generated by VASH. Do not edit by hand.", ""]
    lines.append(body.rstrip("\n"))
    lines.extend(["", "## Agents", ""])
    for name in agent_ids:
        agent = agents.get(name)
        if agent:
            lines.append(f"### {name}")
            lines.append(str(agent.meta.get("description", "")))
            if agent.skills:
                lines.append(f"Skills: {', '.join(agent.skills)}")
            lines.append("")
    lines.extend(["## Skills", "", "Each skill is a folder with SKILL.md (Agent Skills standard) under .agents/skills/.", ""])
    for name in skill_ids:
        skill = skills.get(name)
        if skill:
            lines.append(f"- **{name}** (.agents/skills/{name}/SKILL.md): {skill.meta.get('description', '')}")
    return "\n".join(lines) + "\n"


def load(repo_root: Path, dry_run: bool = False) -> LoadReport:
    """Rebuild CLAUDE.md, AGENTS.md, ai-manifest.json and the installed skills, agents and hooks."""
    written = []
    removed = []
    warnings = []

    try:
        freeze = load_freeze(repo_root)
    except Exception as e:
        return LoadReport(written=[], removed=[], warnings=[f"Failed to load freeze: {e}"])

    from vash.loader.skills import find_agents, find_skills, render_claude_agent

    claude_dir = repo_root / ".claude"
    shared_dir = repo_root / ".agents"
    skills = find_skills(repo_root)
    agents = find_agents(repo_root)

    # The freeze picks catalog skills and agents; the project's own skills/ and agents/ always load.
    wanted_skills = [s["id"] for s in freeze.data.get("skills", [])]
    wanted_skills += [n for n, s in skills.items() if s.origin == "project" and n not in wanted_skills]
    wanted_agents = [a["id"] for a in freeze.data.get("agents", [])]
    wanted_agents += [n for n, a in agents.items() if a.origin == "project" and n not in wanted_agents]

    targets = {
        claude_dir / "skills": "skill",
        shared_dir / "skills": "skill",
        claude_dir / "agents": "agent",
        claude_dir / "hooks": "hook",
    }
    for target in targets:
        removed.extend(_remove_managed(target, dry_run))
        if not dry_run:
            target.mkdir(parents=True, exist_ok=True)

    managed: dict[Path, list[str]] = {t: [] for t in targets}
    for name in wanted_skills:
        skill = skills.get(name)
        if skill is None:
            warnings.append(f"Skill {name} not found in the catalog or in skills/")
            continue
        for folder in (claude_dir / "skills", shared_dir / "skills"):
            dst = folder / name
            if not dry_run:
                shutil.copytree(skill.path, dst, dirs_exist_ok=True)
            written.append(str(dst))
            managed[folder].append(name)

    for name in wanted_agents:
        agent = agents.get(name)
        if agent is None:
            warnings.append(f"Agent {name} not found in the catalog or in agents/")
            continue
        dst = claude_dir / "agents" / f"{name}.md"
        if not dry_run:
            dst.write_text(render_claude_agent(agent), encoding="utf-8", newline="\n")
        written.append(str(dst))
        managed[claude_dir / "agents"].append(dst.name)

    catalog_dir = vash_root() / "catalog"
    hooks_src = catalog_dir / "hooks"
    if hooks_src.exists():
        for h in sorted(hooks_src.iterdir()):
            if h.is_file():
                dst = claude_dir / "hooks" / h.name
                if not dry_run:
                    shutil.copy2(h, dst)
                    dst.chmod(dst.stat().st_mode | 0o111)
                written.append(str(dst))
                managed[claude_dir / "hooks"].append(h.name)

    if not dry_run:
        for target, names in managed.items():
            (target / MANAGED_FILE).write_text("".join(f"{n}\n" for n in names), encoding="utf-8", newline="\n")

    agents_md = repo_root / "AGENTS.md"
    if not dry_run:
        agents_md.write_text(generate_agents_md(repo_root), encoding="utf-8", newline="\n")
    written.append(str(agents_md))

    claude_md = repo_root / "CLAUDE.md"
    content = generate_claude_md(repo_root)
    if not dry_run:
        claude_md.write_text(content, encoding="utf-8", newline="\n")
    written.append(str(claude_md))

    from vash.loader.manifest import generate_manifest
    import json
    manifest = generate_manifest(repo_root)
    manifest_path = repo_root / "ai-manifest.json"
    if not dry_run:
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    written.append(str(manifest_path))

    return LoadReport(written=written, removed=removed, warnings=warnings)
